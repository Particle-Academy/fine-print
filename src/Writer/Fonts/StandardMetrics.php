    /** The width table a face uses (Oblique faces share the upright's). */
    public static function table(string $face): string
    {
        return match ($face) {
            'Helvetica-Oblique' => 'Helvetica',
            'Helvetica-BoldOblique' => 'Helvetica-Bold',
            default => $face,
        };
    }

    /** @return list<int> widths for codes 32..255 */
    public static function widths(string $face): array
    {
        if (str_starts_with($face, 'Courier')) {
            return array_fill(0, 224, 600);
        }

        return self::WIDTHS[self::table($face)];
    }

    /** @return array{ascent: int, descent: int, capHeight: int} */
    public static function vertical(string $face): array
    {
        if (str_starts_with($face, 'Courier')) {
            return self::VERTICAL['Courier'];
        }

        return self::VERTICAL[self::table($face)];
    }
